let a = 100;
a+= 20;
console.log(a); /*will add 20 to 100 because of assignment operation*/

let b = 100;
b-= 20;
console.log(b); /*will subtract 20 */

let c = 40;
c*= 2;
console.log(c); /*will multiply 40 by 2 */

let d = 40;
d/= 2;
console.log(d); /*will divide 40 by 2 */

let e = 40;
e%= 2;
console.log(e); /*will give remainder of 40 divided by 2 */